#!/usr/bin/env python3
"""Generate EventCore's native HUD registry from a REDmod `scripts/` dump.

Usage: gen_native_registry.py <path-to-redmod/scripts> [<eventcore-dir> [<redmod/metadata.json>]]
The optional metadata.json adds the engine's native ink widget classes (inkTextWidget, ...),
which have no script file.

Writes shared/native_registry.lua (server + client validation) and
web/admin/native_registry.js (admin UI pickers) from the same data.
Only class names, parents and blackboard fields are read. Re-run it after the game scripts change.
"""
import json, os, re, sys

scripts = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..")
meta = sys.argv[3] if len(sys.argv) > 3 else os.path.join(scripts, "..", "metadata.json")
CLASS = re.compile(r"^\s*(?:(?:importonly|import|abstract|public|native|final)\s+)*class\s+(\w+)(?:\s+extends\s+(\w+))?", re.M)
VAR = re.compile(r"^\s*var\s+(\w+)\s*:\s*BlackboardID_(\w+)\s*;", re.M)

parents, files, bodies = {}, {}, {}
for root, _, names in os.walk(scripts):
    for name in sorted(names):
        if not name.endswith(".script"):
            continue
        path = os.path.join(root, name)
        text = open(path, encoding="utf-8", errors="replace").read()
        matches = list(CLASS.finditer(text))
        for i, m in enumerate(matches):
            cls, parent = m.group(1), m.group(2) or ""
            parents[cls] = parent
            files[cls] = os.path.relpath(path, scripts).replace(os.sep, "/")
            end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
            bodies[cls] = text[m.end():end]

def chain(cls):
    seen = []
    while cls and cls in parents and cls not in seen:
        seen.append(cls)
        cls = parents[cls]
    if cls:
        seen.append(cls)  # root that has no script definition, e.g. inkWidget
    return seen

def derives(cls, base):
    return base in chain(cls)

native_parents = {}
if os.path.exists(meta):
    for c in json.load(open(meta, encoding="utf-8")).get("classes", []):
        native_parents[c["name"]] = c.get("parent", "")
    for name, parent in native_parents.items():
        if name not in parents:
            parents[name] = parent
            files[name] = "(engine native)"
            bodies[name] = ""

widgets, controllers, boards, layers = [], [], [], []
for cls in sorted(parents):
    c = chain(cls)
    if "inkLayer" in c and cls != "inkLayer" and "Definition" not in cls and "_" not in cls:
        layers.append({"n": cls, "p": parents[cls], "f": files[cls]})
    elif "inkWidget" in c:
        widgets.append({"n": cls, "p": parents[cls], "f": files[cls]})
    elif "inkLogicController" in c or "inkGameController" in c:
        controllers.append({"n": cls, "f": files[cls], "hud": "inkHUDGameController" in c})
    elif "BlackboardDefinition" in c and cls != "BlackboardDefinition":
        fields = [[a, b] for a, b in VAR.findall(bodies[cls])]
        if fields:
            boards.append({"n": cls, "f": files[cls], "v": fields})

data = {"schema": 1, "source": os.path.basename(os.path.dirname(os.path.abspath(scripts))) or "redmod",
        "layers": layers, "widgets": widgets, "controllers": controllers, "blackboards": boards}

def q(s):
    return json.dumps(s)

lines = ["-- GENERATED by tools/gen_native_registry.py from the game's REDscript dump. Do not edit by hand.",
         "-- Names only: this file lists what exists in the game scripts, not what Open77 accepts.",
         "EventCore = EventCore or {}",
         "EventCore.NativeRegistry = {",
         "    schema = 1,"]
lines.append("    -- inkHUDLayer is the layer the in-game HUD controllers live in.\n    layers = {")
for l in layers:
    lines.append("        { n = %s, p = %s }," % (q(l["n"]), q(l["p"])))
lines.append("    },\n    widgets = {")
for w in widgets:
    lines.append("        { n = %s, p = %s, f = %s }," % (q(w["n"]), q(w["p"]), q(w["f"])))
lines.append("    },\n    controllers = {")
for c in controllers:
    lines.append("        { n = %s, f = %s, hud = %s }," % (q(c["n"]), q(c["f"]), str(c["hud"]).lower()))
lines.append("    },\n    blackboards = {")
for b in boards:
    vs = ", ".join("{ %s, %s }" % (q(a), q(t)) for a, t in b["v"])
    lines.append("        { n = %s, f = %s, v = { %s } }," % (q(b["n"]), q(b["f"]), vs))
lines.append("    },\n}\n")
lines.append("""local index = { layer = {}, widget = {}, controller = {}, blackboard = {} }
for _, entry in ipairs(EventCore.NativeRegistry.layers) do index.layer[entry.n] = entry end
for _, entry in ipairs(EventCore.NativeRegistry.widgets) do index.widget[entry.n] = entry end
for _, entry in ipairs(EventCore.NativeRegistry.controllers) do index.controller[entry.n] = entry end
for _, entry in ipairs(EventCore.NativeRegistry.blackboards) do index.blackboard[entry.n] = entry end

--- Returns the registry entry and its kind ("layer" | "widget" | "controller" | "blackboard") or nil.
function EventCore.NativeRegistry.Find(name)
    if type(name) ~= "string" then return nil end
    for _, kind in ipairs({ "layer", "controller", "widget", "blackboard" }) do
        local entry = index[kind][name]
        if entry then return entry, kind end
    end
    return nil
end
""")
open(os.path.join(out, "shared", "native_registry.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
open(os.path.join(out, "web", "admin", "native_registry.js"), "w", encoding="utf-8", newline="\n").write(
    "// GENERATED by tools/gen_native_registry.py. Do not edit by hand.\nwindow.EC_NATIVE = " + json.dumps(data, separators=(",", ":")) + ";\n")
print("layers %d, widgets %d, controllers %d (hud %d), blackboards %d" % (
    len(layers), len(widgets), len(controllers), sum(c["hud"] for c in controllers), len(boards)))
